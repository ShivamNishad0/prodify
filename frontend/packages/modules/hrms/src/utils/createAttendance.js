async function hitApi(empData) {
  const createdAttendance = [];
  for (let i = 0; i < 30; i++) {
    createdAttendance.push({
      day: "d" + (i + 1),
      inTime: "10:53",
      outTime: "20:25",
      status: i < empData.Attendance ? "PRESENTS" : "ABSENT",
    });
  }
  const payload = {
    attendance: createdAttendance,
    createdBy: 9,
    empNo: empData.EmpCode,
    monthName: "JUNE",
    year: 2024,
    zoneId: 101,
  };
  return payload;
}

